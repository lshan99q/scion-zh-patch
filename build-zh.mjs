import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT = process.env.SCION_ROOT || (process.env.HOME || '') + '/src/scion';
const SRC_DIST = path.join(ROOT, 'web/dist/client');
const OUT = process.env.OUT_DIR || path.join(ROOT, 'zh-dist');
const ZH_DIR = new URL('.', import.meta.url).pathname;
const DICT_FILE = path.join(ZH_DIR, 'patch/zh-CN.json');

const dict = JSON.parse(fs.readFileSync(DICT_FILE, 'utf8'));
const patterns = fs.readFileSync(path.join(ZH_DIR, 'patch/zh-patterns.js'), 'utf8');
const runtime = fs.readFileSync(path.join(ZH_DIR, 'patch/runtime.js'), 'utf8');

const payload =
  '/* scion-zh: generated by web-zh/build-zh.mjs — do not edit here */\n' +
  'window.__SCION_ZH__=' +
  JSON.stringify(dict) +
  ';\n' +
  patterns +
  '\n' +
  runtime;

// 1) 复制原始构建产物
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
execSync(`cp -a ${SRC_DIST}/. ${OUT}/`);

// 2) 写入补丁脚本
fs.writeFileSync(path.join(OUT, 'assets/scion-zh.js'), payload);

// 3) 在入口模块末尾挂载补丁
const mainFile = path.join(OUT, 'assets/main.js');
let main = fs.readFileSync(mainFile, 'utf8');
if (!main.includes("import './scion-zh.js'")) main += "\nimport './scion-zh.js';\n";
fs.writeFileSync(mainFile, main);

// 4) 丢弃过期的预压缩变体，并按新内容重新生成 gzip
for (const f of ['assets/main.js', 'assets/scion-zh.js']) {
  const abs = path.join(OUT, f);
  for (const suffix of ['.br', '.gz']) fs.rmSync(abs + suffix, { force: true });
  execSync(`gzip -9 -c ${abs} > ${abs}.gz`);
}

console.log('dict entries:', Object.keys(dict).length);
console.log('payload bytes:', payload.length);
console.log('out:', OUT);
console.log('main.js hook:', main.includes("import './scion-zh.js'") ? 'ok' : 'MISSING');
